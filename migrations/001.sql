 status VARCHAR(50) NOT NULL,
 FOREIGN KEY (purchase_id) REFERENCES purchases(id) ON DELETE RESTRICT,
 FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE RESTRICT
